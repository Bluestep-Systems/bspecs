// node --test tools/  (from the plugin root). Never touches the network: fetch is stubbed.
import { test } from "node:test";
import assert from "node:assert/strict";
import { existsSync, mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { NAMES, bannerProblem, fetchTypes } from "../fetch-types.mjs";

const good = "/**\n * GENERATED by the host. Do not edit.\n */\nexport interface X {}\nconst a: HTMLElement = null as any;\n";
const reply = (status, body) => ({ ok: status >= 200 && status < 300, status, text: async () => body });

test("there are seven names", () => {
  assert.equal(NAMES.length, 7);
  assert.ok(NAMES.includes("component-host") && NAMES.includes("ui.icons"));
});

test("banner check accepts a generated file, even one that mentions HTMLElement", () => {
  assert.equal(bannerProblem(good), null);
});

test("banner check rejects index.html, a missing banner and a missing export", () => {
  assert.match(bannerProblem("<!doctype html><html></html>"), /doc comment/);
  assert.match(bannerProblem("/**\n * hand written\n */\nexport const a = 1;\n"), /GENERATED/);
  assert.match(bannerProblem("/**\n * GENERATED\n */\nconst a = 1;\n"), /export/);
});

test("fetchTypes writes all seven from https://<host>/one/<name>.d.ts", async (t) => {
  const out = mkdtempSync(path.join(tmpdir(), "types-"));
  t.after(() => rmSync(out, { recursive: true, force: true }));
  const urls = [];
  const results = await fetchTypes({ host: "one.example.test", out, fetchFn: async (url) => (urls.push(url), reply(200, good)) });
  assert.ok(results.every((r) => r.ok));
  assert.deepEqual(urls, NAMES.map((n) => `https://one.example.test/one/${n}.d.ts`));
  for (const n of NAMES) assert.equal(readFileSync(path.join(out, `${n}.d.ts`), "utf8"), good);
});

test("fetchTypes keeps nothing from a failing file and reports it", async (t) => {
  const out = mkdtempSync(path.join(tmpdir(), "types-"));
  t.after(() => rmSync(out, { recursive: true, force: true }));
  const fetchFn = async (url) => {
    if (url.endsWith("/ui.d.ts")) return reply(200, "<!doctype html><html></html>");
    if (url.endsWith("/form-kit.d.ts")) return reply(404, "");
    if (url.endsWith("/ui.icons.d.ts")) throw new Error("offline");
    return reply(200, good);
  };
  const results = await fetchTypes({ host: "h.test", out, fetchFn });
  const bad = results.filter((r) => !r.ok).map((r) => r.name).sort();
  assert.deepEqual(bad, ["form-kit", "ui", "ui.icons"]);
  assert.ok(!existsSync(path.join(out, "ui.d.ts")));
  assert.ok(existsSync(path.join(out, "component-host.d.ts")));
  assert.match(results.find((r) => r.name === "form-kit").detail, /HTTP 404/);
  assert.match(results.find((r) => r.name === "ui.icons").detail, /offline/);
});
